"""Generate docs/merged-table-summary.md from the built table (deterministic, no timestamps).

The summary reports row counts, per-column null rates, data-availability
crosstabs and automated data-quality findings.

It deliberately does NOT cross-tabulate measured against predicted sign, or
"wired" against "functionally connected". Those tables would preview the
sizes of channel categories A–E before the classification rubric is frozen.
That would contaminate the later blind classification pass, which the brief
forbids.
"""

from __future__ import annotations

import json
from collections import Counter

from src.acquire.common import REPO_ROOT
from src.merge.build_table import COLUMN_ORDER, OUT_DIR, STATES, TABLE

DOC = REPO_ROOT / "docs" / "merged-table-summary.md"


def _pct(n: int, d: int) -> str:
    return f"{100.0 * n / d:.2f}%" if d else "n/a"


def _avail(v) -> str:
    if v is None:
        return "null"
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return ">0" if v > 0 else "0"
    return "present"


def _table(header: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def _crosstab(rows, row_key, col_key, row_order=None, col_fmt=lambda v: v):
    ct = Counter((r[row_key], col_fmt(r[col_key])) for r in rows)
    rvals = row_order or sorted({k[0] for k in ct}, key=str)
    cvals = sorted({k[1] for k in ct}, key=str)
    body = [[rv] + [ct.get((rv, cv), 0) for cv in cvals] + [sum(ct.get((rv, cv), 0) for cv in cvals)] for rv in rvals]
    return _table([f"{row_key} \\ {col_key}"] + [str(c) for c in cvals] + ["total"], body)


def generate() -> str:
    import pyarrow.parquet as pq

    tbl = pq.read_table(OUT_DIR / f"{TABLE}.parquet")
    rows = tbl.to_pylist()
    n = len(rows)
    sums = (OUT_DIR / "SHA256SUMS").read_text(encoding="utf-8")
    meta = json.loads((OUT_DIR / f"{TABLE}.columns.json").read_text(encoding="utf-8"))
    cfg = {k: v for k, v in meta["_table"]["config"].items() if not k.startswith("_")}
    excl = (OUT_DIR / f"{TABLE}_exclusions.csv").read_text(encoding="utf-8").splitlines()
    heads = sorted({r["pre"] for r in rows})

    out = []
    out.append("# Merged edge table: summary\n")
    out.append("Generated by `python -m src.build` from `data/processed/merged_edges.parquet`. "
               "Every number below is computed from the table itself. **No pair is classified into channel "
               "categories A–E.**\n")
    out.append("## Identity\n")
    out.append("```\n" + sums + "```\n")
    out.append(f"- Rows: **{n:,}** = {len(heads)} head neurons × {len(heads) - 1} partners "
               f"(ordered pairs, self-pairs {'included' if cfg['include_self_pairs'] else 'excluded'}).")
    out.append(f"- Columns: {len(COLUMN_ORDER)}. Per-column definition, source files (with SHA-256) and paper: "
               "`data/processed/merged_edges.columns.json`.")
    out.append(f"- Configuration (all PROVISIONAL, see `docs/decisions.md`): `{json.dumps(cfg, sort_keys=True)}`")
    out.append(f"- Randi atlas release: {cfg['randi_release']}. "
               "Every source is a SECONDARY copy; the primary comparison is pending. **This blocks the freeze** (D-003).\n")

    out.append("## Per-column null rates\n")
    body = []
    for c in COLUMN_ORDER:
        nulls = sum(1 for r in rows if r[c] is None)
        body.append([f"`{c}`", nulls, _pct(nulls, n)])
    out.append(_table(["column", "null rows", "null rate"], body) + "\n")
    out.append("Nulls mean the value does not exist for that pair, never that it was imputed as zero. "
               "`source_flags` gives the reason per row.\n")

    out.append("## Measurement coverage (Rule 2: tested vs never tested)\n")
    st = Counter(r["randi_state_wt"] for r in rows)
    su = Counter(r["randi_state_unc31"] for r in rows)
    out.append(_table(["state", "WT rows", "unc-31 rows"], [[s, st.get(s, 0), su.get(s, 0)] for s in STATES]) + "\n")
    out.append(f"- `randi_tested` (WT observed at least once): {sum(r['randi_tested'] for r in rows):,} of {n:,}.")
    both = sum(1 for r in rows if r["measured_q_wt"] is not None and r["measured_q_unc31"] is not None)
    out.append(f"- Pairs with a WT q-value and an unc-31 q-value: {both:,}. `unc31_delta` exists for "
               f"{sum(1 for r in rows if r['unc31_delta'] is not None):,}.")
    out.append(f"- Authors' strict candidate extrasynaptic pairs (`randi_strict_extrasynaptic_candidate`): "
               f"{sum(r['randi_strict_extrasynaptic_candidate'] for r in rows)}.\n")
    out.append("WT state × unc-31 state:\n")
    out.append(_crosstab(rows, "randi_state_wt", "randi_state_unc31", list(STATES)) + "\n")

    out.append("## Data availability by measurement state\n")
    out.append("These tables show whether a value **exists** (null), is zero, or is positive. "
               "They do not say whether values agree.\n")
    for col in ("anat_chem_white", "anat_chem_witvliet", "anat_gap", "np_edge_short"):
        out.append(f"### `{col}`\n")
        out.append(_crosstab(rows, "randi_state_wt", col, list(STATES), _avail) + "\n")
    out.append("### `predicted_sign` (existence only)\n")
    out.append(_crosstab(rows, "randi_state_wt", "predicted_sign", list(STATES), _avail) + "\n")
    out.append("### `monoamine_edge` (existence only)\n")
    out.append(_crosstab(rows, "randi_state_wt", "monoamine_edge", list(STATES),
                         lambda v: "null" if v is None else ("none" if v == "none" else "present")) + "\n")

    out.append("## Row flags\n")
    fc = Counter(f for r in rows for f in (r["source_flags"].split(";") if r["source_flags"] else []))
    out.append(_table(["flag", "rows"], [[f"`{k}`", v] for k, v in sorted(fc.items())]) + "\n")

    out.append("## Exclusions (nothing dropped silently)\n")
    cats = Counter()
    for line in excl[1:]:
        cat = line.split(",", 1)[0]
        cats[cat] += 1
    out.append(_table(["category", "log lines"], [[k, v] for k, v in sorted(cats.items())]))
    out.append("\nFull log: `data/processed/merged_edges_exclusions.csv`. Name-level exclusions are in "
               "`data/interim/namespace/exclusions.csv`.\n")

    out.append("## Things that look wrong, or need attention\n")
    findings = []
    und = [r for r in rows if r["source_flags"] and "wt_connected_but_mean_dFF_undefined" in r["source_flags"]]
    for r in und:
        findings.append(f"`{r['pre']}`→`{r['post']}` is WT-connected (q={r['measured_q_wt']:.3g}) but has no defined "
                        "mean dF/F (single trial, NaN). `measured_sign_wt` = `undefined`.")
    for s_ in ("wt", "unc31"):
        qq = sum(1 for r in rows if f"{s_}_q_and_q_eq_both_below_0.05" in r["source_flags"])
        conn = sum(1 for r in rows if r[f"randi_state_{s_}"] == "connected")
        if qq:
            findings.append(f"{qq} of {conn} {s_} `connected` pairs ALSO pass the authors' equivalence test "
                            f"(q_eq<0.05): their response differs significantly from control but lies within the "
                            "authors' equivalence margin (q_eq_th = 1.2; ±1.2 × control SD per their code, unverified for this file), i.e. it is significant but small. They are kept as "
                            "`connected` and flagged `{s_}_q_and_q_eq_both_below_0.05`. A classification rubric "
                            "should decide explicitly how to treat them.".replace("{s_}", s_))
    awc = sum(1 for r in rows if "awc_identity_unresolved" in r["source_flags"])
    findings.append(f"{awc} rows involve AWCON/AWCOFF and carry no anatomical, polarity or extrasynaptic values under "
                    f"`awc_policy={cfg['awc_policy']}` (ON/OFF ↔ L/R is random per animal).")
    rmhr = [r for r in rows if "RMHR" in (r["pre"], r["post"])]
    findings.append(f"RMHR ({len(rmhr)} rows) is a head neuron missing from the authors' head list; it is never observed "
                    "in the atlas (`not_observed`).")
    cov = {k: sum(1 for r in rows if r[k] is None) for k in ("anat_chem_white", "anat_chem_witvliet")}
    findings.append(f"Anatomical coverage is partial: `anat_chem_white` (N2U head series) is null for {cov['anat_chem_white']:,} "
                    f"rows and `anat_chem_witvliet` for {cov['anat_chem_witvliet']:,}. Pharyngeal and "
                    "retrovesicular-ganglion neurons lie outside those reconstructions. `anat_chem_white_whole` "
                    "(the Varshney compilation Randi used) covers them.")
    lat0 = sum(1 for r in rows if r["randi_state_wt"] == "connected" and r["measured_peak_time_wt"] == 0)
    findings.append(f"{lat0} WT-connected pairs have their kernel peak at t=0, so rise time = 0: the fitted impulse "
                    "response is maximal at stimulus onset. Peak times are resolved at 0.2 s (authors' 0–200 s, "
                    "1,000-point axis). `measured_latency_wt` is derived from the atlas kernels; the authors' own "
                    "per-trial rise times are not in the release.")
    findings.append("Every source is a secondary copy (PyPI / GitHub). Primary comparisons are pending and block "
                    "the freeze. Five published numbers do not reproduce; see `tests/test_reproduction.py` "
                    "(strict xfail BLOCKER tests).")
    out.extend(f"- {f}" for f in findings)
    out.append("")
    return "\n".join(out) + "\n"


def write() -> str:
    text = generate()
    DOC.write_text(text, encoding="utf-8")
    return text
