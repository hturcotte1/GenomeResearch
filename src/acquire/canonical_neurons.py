_VNC_NUMBERED = re.compile(r"(AS|DA|DB|DD|VA|VB|VC|VD)(\d+)")


def _text(name: str) -> str:
    return (RAW_ROOT / SOURCE_ID / name).read_bytes().decode("utf-8")


def _byte_facts(name: str) -> dict:
    data = (RAW_ROOT / SOURCE_ID / name).read_bytes()
    return {
        "crlf_line_endings": b"\r\n" in data,
        "ends_with_newline": data.endswith(b"\n"),
    }


def _cells_py_lists() -> dict[str, list[str]]:
    """Resolve Cells.py's top-level string-list assignments without executing it.

    Handled: a list/tuple of string literals, a bare name, and ``+`` of those,
    in file order (a later assignment replaces an earlier one). A name that is
    also mutated anywhere (``.append``/``.extend``/``+=``/item assignment) or
    assigned from anything else is dropped, along with every list built from it.
    """
    tree = ast.parse(_text(F_CELLS_PY))
    mutated: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and isinstance(node.func.value, ast.Name):
            if node.func.attr in ("append", "extend", "insert", "remove", "pop", "sort", "reverse"):
                mutated.add(node.func.value.id)
        if isinstance(node, ast.AugAssign) and isinstance(node.target, ast.Name):
            mutated.add(node.target.id)
        if isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Subscript) and isinstance(t.value, ast.Name):
                    mutated.add(t.value.id)

    env: dict[str, list[str]] = {}

    def ev(node):
        if isinstance(node, (ast.List, ast.Tuple)):
            out = []
            for elt in node.elts:
                if not (isinstance(elt, ast.Constant) and isinstance(elt.value, str)):
                    return None
                out.append(elt.value)
            return out
        if isinstance(node, ast.Name):
            return list(env[node.id]) if node.id in env else None
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
            left, right = ev(node.left), ev(node.right)
            return None if left is None or right is None else left + right
        return None

    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            value = None if name in mutated else ev(node.value)
            if value is None:
                env.pop(name, None)
            else:
                env[name] = value
    return env


def _cells_py_asserts_302() -> list[str]:
    """Source text of every top-level ``assert`` in Cells.py that mentions 302."""
    src = _text(F_CELLS_PY)
    out = []
    for node in ast.parse(src).body:
        if isinstance(node, ast.Assert):
            seg = ast.get_source_segment(src, node)
            if seg and "302" in seg:
                out.append(seg)
    return sorted(out)


def _individual_neurons() -> tuple[str, list[list[str]]]:
    """(first line, data rows). Rows read with csv.reader(delimiter=';'), as the toolbox does."""
    text = _text(F_INDIVIDUAL)
    first = text.split("\n", 1)[0]
    rows = [r for r in csv.reader(io.StringIO(text), delimiter=";") if r and not r[0].startswith("#")]
    return first, rows


