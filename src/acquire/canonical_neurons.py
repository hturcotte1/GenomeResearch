"""Candidate lists of C. elegans hermaphrodite neuron names, for the Phase 2 namespace.

Phase 2 needs a WormAtlas-standard neuron list (White et al. 1986 naming) as
the single source of truth for canonical names. wormatlas.org is blocked in
this environment, so this module acquires every reachable candidate and
records exactly what each one says. It does not build the namespace, choose a
candidate, or apply any naming rule; those are the owner's decisions
(docs/decisions.md D-009). See docs/provenance/canonical_neurons.md.

Candidates acquired (all SECONDARY copies):

1. ``IndividualNeurons.csv`` (ConnectomeToolbox): a copy of WormAtlas's
   neuron-names table. Its first line says "Data taken from
   https://wormatlas.org/NeuronNames.htm". ``;``-separated: name; expanded
   name; lineage; description. Hermaphrodite and male neurons together.
2. ``Cells.py`` (ConnectomeToolbox source code, acquired as a raw text file;
   it is only parsed with ``ast``, never imported or executed). Holds the
   literal list ``PREFERRED_HERM_NEURON_NAMES`` (302 names) and the Cook et
   al. 2019 category lists the toolbox builds the same 302 from. Header:
   "Much of this data taken from supplementary info of Cook et al 2019".
3. ``all_cell_info.csv`` (ConnectomeToolbox): generated by the toolbox
   (``cect/CellInfo.py``) from 2 and 1 plus WormAtlas colour-code
   classes. A derived table, not an independent list.
4. ``C. elegans Cell List - WormAtlas.tsv`` (OpenWorm owmeta @ 945f717): a
   copy of WormAtlas's "Complete Cell List" (celllist.htm): every cell, not
   only neurons, with lineage name and description. No neuron flag.
5. ``C. elegans Cell List - WormBase.csv`` (same commit): OpenWorm's cell
   spreadsheet "originally sourced from WormBase and WormAtlas", with 0/1
   columns such as "Neurons (no male-specific cells)" and a totals row.
6. ``neurons.csv`` (same commit): OpenWorm's 302-row neuron table
   (name;type;lineage). Its origin is not documented in the distribution.
7. ``cell_lineage.txt`` (``wormneuroatlas`` 0.0.7.3 wheel): another copy of
   the WormAtlas complete cell list, as used by Randi's ``CellLineage`` class.
   It differs from 4 (see ``record_counts``).
8. ``neuron_ids.txt`` (same wheel): the 300-id list of Randi et al.'s atlas
   package (no CANL/CANR; AWCON/AWCOFF instead of AWCL/AWCR). Byte-identical
   to ``randi2023``'s copy.
9. ``nemanode_da8ca7e__neurons.json`` (zhenlab-ltri/NemaNode @ da8ca7e):
   NemaNode's cell table, the only candidate with an explicit per-cell class
   field. Byte-identical to ``white1986``'s copy.

Facts later phases must respect (each checked by ``record_counts``):

- Cells.py, the WormBase.csv neuron column and neurons.csv name exactly the
  same 302 names. All 302 occur in IndividualNeurons.csv and in NemaNode.
- Neither WormAtlas cell-list copy (4, 7) writes AVFL, AVFR, DB1 or DB3.
  They write ``AVFL/R`` (twice), ``DB1/3`` and ``DB3/1``. The wheel copy (7)
  also lacks PHBR: it writes ``PHRB`` with PHBR's lineage, and repeats ADFL.
- AWC is AWCL/AWCR everywhere except ``neuron_ids.txt`` (AWCON/AWCOFF).
- No candidate zero-pads ventral-cord names (VB1, not VB01).
- Lineages are not consistent across copies: AVFL/AVFR have P1.aaaa and
  W.aaa in opposite order in WormBase.csv and neurons.csv; PVR is C.aappa or
  C.aappv; RIPR is AB.prappaaaa or AB arappaaaa, depending on the file.
"""

