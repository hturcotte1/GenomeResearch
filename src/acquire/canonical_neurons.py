def _wna_ids() -> list[list[str]]:
    return [line.split() for line in _text(F_WNA_IDS).splitlines() if line.strip()]


def _dups(names: list[str]) -> dict[str, int]:
    return {k: v for k, v in sorted(Counter(names).items()) if v > 1}


def _probe(names: list[str], pharyngeal: list[str], list_lowercase: bool) -> dict:
    """Name-style facts for one candidate list, on names exactly as written."""
    s = set(names)
    lower = sorted(n for n in s if any(c.islower() for c in n))
    vnc = sorted(n for n in s if _VNC_NUMBERED.fullmatch(n))
    return {
        "entries": len(names),
        "distinct": len(s),
        "duplicated_names": _dups(names),
        "has_CANL": "CANL" in s,
        "has_CANR": "CANR" in s,
        "awc_names": sorted(n for n in s if n.startswith("AWC")),
        "pharyngeal20_present": sum(1 for p in pharyngeal if p in s),
        "pharyngeal20_missing": sorted(p for p in pharyngeal if p not in s),
        "vnc_numbered_names": len(vnc),
        "vnc_numbered_names_zero_padded": sorted(n for n in vnc if _VNC_NUMBERED.fullmatch(n).group(2).startswith("0")),
        "names_containing_slash": sorted(n for n in s if "/" in n),
        "names_with_surrounding_whitespace": sorted(repr(n) for n in s if n != n.strip()),
        "names_with_lowercase_count": len(lower),
        "names_with_lowercase": lower if list_lowercase else "not listed for all-cell sets (see count)",
    }


def record_counts() -> dict:
    """Counts computed from the raw files only, with no naming decisions applied.

    Names are compared exactly as written (case, whitespace and slashes kept).
    Definitions:

    Name sets (the ``sets`` key gives their sizes):

    - ``cellspy302``: Cells.py literal ``PREFERRED_HERM_NEURON_NAMES``.
    - ``wormbase_herm``: WormBase.csv rows (after the 3 heading rows) whose
      column "Neurons (no male-specific cells)" is "1".
    - ``wormbase_male``: same, column "Neurons (male-specific)".
    - ``ow_neurons``: neurons.csv column 1.
    - ``wna_ids``: neuron_ids.txt column 2 (column 1 is a 0-based index).
    - ``individual``: IndividualNeurons.csv column 1, comment line skipped.
    - ``nemanode``: every ``name`` in the NemaNode cell table (all cell
      types, not only neurons).
    - ``wa_tsv`` / ``cell_lineage``: column 1 of the two WormAtlas cell-list
      copies, header line skipped (all cells, not only neurons).
    - ``all_cell_info``: column 1 of all_cell_info.csv, header skipped.

    Per-set probes (``probe``): entries and distinct names; duplicated names
    with their counts; CANL/CANR presence; names starting "AWC";
    ``pharyngeal20`` = how many of the 20 names Cells.py lists as
    PHARYNGEAL_INTERNEURONS + PHARYNGEAL_MOTORNEURONS +
    PHARYNGEAL_POLYMODAL_NEURONS are present, and which are missing;
    ``vnc_numbered_names`` = names matching (AS|DA|DB|DD|VA|VB|VC|VD)<digits>
    exactly, and those whose number starts with 0; names containing "/";
    names with leading/trailing whitespace; names with any lower-case letter
    (count always; the names are listed only for the neuron lists, since in
    the all-cell sets they are the many non-neuron cells such as ``pm1``).

    ``diff``: exact set differences ``A_minus_B`` between the neuron-list
    sets (cellspy302, wormbase_herm, ow_neurons, wna_ids, individual), both
    ways. For the all-cell sets only the direction "neuron list minus cell
    set" is listed; the other direction is counted. ``wormbase_male`` is
    compared only with cellspy302 (intersection) and individual (both ways,
    the second after removing cellspy302).

    ``lineage_comparison_over_cellspy302``: for each pair of files that give
    a lineage per name (individual, ow_neurons, wormbase_herm, wa_tsv,
    cell_lineage), over the cellspy302 names present in both as written:
    how many have identical lineage strings, and the names whose lineages
    still differ when the first space is read as "." (a comparison aid for
    the "AB plapaaaapp" vs "AB.plapaaaapp" styles; nothing is rewritten).

    ``rows_for_probe_names``: the raw rows, per file, for AVFL, AVFR,
    AVFL/R, DB1, DB3, DB1/3, DB3/1, PHBR, PHRB and ADFL, i.e. the names
    whose spelling or multiplicity differs between copies.

    ``classes``: the only explicit class assignment is NemaNode's
    ``classes`` field. ``nemanode_classes_over_cellspy302`` counts distinct
    values over the cellspy302 names (each looked up exactly);
    ``nemanode_classes_over_pharyngeal20`` does the same over the 20
    pharyngeal names above. No class count is derived for the other files,
    because that would need a naming rule.

    ``cell_list_copies``: line-level comparison of the two WormAtlas cell-list
    copies. ``rows_identical`` compares lines as written;
    ``rows_identical_if_lineage_space_equals_dot`` treats the first space in
    the lineage field as "." (the wheel writes "AB plapaaaapp" where the
    OpenWorm copy writes "AB.plapaaaapp"), reported side by side.
    """
    raw = RAW_ROOT / SOURCE_ID
    out: dict = {}

    # --- Cells.py -----------------------------------------------------------
    env = _cells_py_lists()
    cellspy302 = env["PREFERRED_HERM_NEURON_NAMES"]
    pharyngeal = (
        env["PHARYNGEAL_INTERNEURONS"] + env["PHARYNGEAL_MOTORNEURONS"] + env["PHARYNGEAL_POLYMODAL_NEURONS"]
    )
    cook = env.get("PREFERRED_HERM_NEURON_NAMES_COOK")
    out["cells_py"] = {
        "PREFERRED_HERM_NEURON_NAMES_len": len(cellspy302),
        "PREFERRED_HERM_NEURON_NAMES_sorted": cellspy302 == sorted(cellspy302),
        "PREFERRED_HERM_NEURON_NAMES_COOK_resolved_statically": cook is not None,
        "PREFERRED_HERM_NEURON_NAMES_COOK_len": None if cook is None else len(cook),
        "PREFERRED_HERM_NEURON_NAMES_COOK_same_set": None if cook is None else set(cook) == set(cellspy302),
        "asserts_mentioning_302": _cells_py_asserts_302(),
        "pharyngeal20_names": sorted(pharyngeal),
        "UNKNOWN_FUNCTION_NEURONS": env.get("UNKNOWN_FUNCTION_NEURONS"),
        "group_sizes": {
            k: (len(env[k]) if k in env else None)
            for k in sorted(
                (
                    "SENSORY_NEURONS_COOK",
                    "INTERNEURONS_COOK",
                    "MOTORNEURONS_COOK",
                    "PHARYNGEAL_NEURONS",
                    "PHARYNGEAL_POLYMODAL_NEURONS",
                    "UNKNOWN_FUNCTION_NEURONS",
                    "MALE_SPECIFIC_NEURONS",
                    "VENTRAL_CORD_MOTORNEURONS",
                )
            )
        },
        **_byte_facts(F_CELLS_PY),
    }

    # --- IndividualNeurons.csv ---------------------------------------------
    first_line, in_rows = _individual_neurons()
    individual = [r[0] for r in in_rows]
    out["individual_neurons_csv"] = {
        "first_line": first_line,
        "data_rows": len(in_rows),
        "fields_per_row": {str(k): v for k, v in sorted(Counter(len(r) for r in in_rows).items())},
        **_byte_facts(F_INDIVIDUAL),
    }

    # --- WormBase.csv -------------------------------------------------------
    wb = _wormbase_csv()
    header, totals, data = wb[1], wb[2], wb[3:]
    col_herm = header.index("Neurons (no male-specific cells)")
    col_male = header.index("Neurons (male-specific)")
    wormbase_herm = [r[0] for r in data if r[col_herm] == "1"]
    wormbase_male = [r[0] for r in data if r[col_male] == "1"]
    flagged = {}
    for j, h in enumerate(header):
        if h and totals[j]:
            flagged[h] = {"totals_row": totals[j], "rows_marked_1": sum(1 for r in data if r[j] == "1")}
    out["wormbase_csv"] = {
        "row0_title": wb[0][1],
        "header": header,
        "data_rows": len(data),
        "fields_per_row": {str(k): v for k, v in sorted(Counter(len(r) for r in wb).items())},
        "totals_row_vs_rows_marked_1": flagged,
        "herm_neuron_rows_with_WormBase_ID": sum(1 for r in data if r[col_herm] == "1" and r[header.index("WormBase ID")]),
        **_byte_facts(F_WB_CSV),
    }

    # --- neurons.csv --------------------------------------------------------
    ow = _ow_neurons()
    ow_neurons = [r[0] for r in ow]
    out["openworm_neurons_csv"] = {
        "rows": len(ow),
        "fields_per_row": {str(k): v for k, v in sorted(Counter(len(r) for r in ow).items())},
        "type_values": len({r[1] for r in ow}),
        **_byte_facts(F_OW_NEURONS),
    }

    # --- neuron_ids.txt -----------------------------------------------------
    ids_rows = _wna_ids()
    wna_ids = [r[1] for r in ids_rows]
    out["wna_neuron_ids_txt"] = {
        "rows": len(ids_rows),
        "fields_per_row": {str(k): v for k, v in sorted(Counter(len(r) for r in ids_rows).items())},
        "index_column_is_0_to_n_minus_1": [int(r[0]) for r in ids_rows] == list(range(len(ids_rows))),
        "ids_alphabetically_sorted": wna_ids == sorted(wna_ids),
        **_byte_facts(F_WNA_IDS),
    }

    # --- NemaNode -----------------------------------------------------------
    nn = json.loads((raw / F_NEMANODE).read_text(encoding="utf-8"))
    nn_by_name = {e["name"]: e for e in nn}
    nemanode = [e["name"] for e in nn]
    cls302 = Counter(nn_by_name[n]["classes"] for n in cellspy302 if n in nn_by_name)
    cls_wna = Counter(nn_by_name[n]["classes"] for n in wna_ids if n in nn_by_name)
    out["nemanode_neurons_json"] = {
        "entries": len(nn),
        "keys": sorted({k for e in nn for k in e}),
        "distinct_classes_all_entries": len({e["classes"] for e in nn}),
        "typ_values_all_entries": dict(sorted(Counter(e["typ"] for e in nn).items())),
        "typ_values_cellspy302": dict(sorted(Counter(nn_by_name[n]["typ"] for n in cellspy302 if n in nn_by_name).items())),
    }
    out["classes"] = {
        "nemanode_classes_over_cellspy302": len(cls302),
        "nemanode_class_sizes_over_cellspy302": dict(sorted(cls302.items())),
        "nemanode_classes_over_pharyngeal20": len({nn_by_name[n]["classes"] for n in pharyngeal if n in nn_by_name}),
        "nemanode_classes_over_wna_ids_found": len(cls_wna),
        "wna_ids_not_in_nemanode": sorted(n for n in wna_ids if n not in nn_by_name),
        "derivable_from_other_files": "no explicit class field; a class count would need a naming rule (Phase 2)",
    }

    # --- WormAtlas cell-list copies -----------------------------------------
    tsv = _tab_rows(F_WA_TSV)
    cl = _tab_rows(F_LINEAGE)
    wa_tsv = [r[0] for r in tsv[1:]]
    cell_lineage = [r[0] for r in cl[1:]]

    def _dot(row: list[str]) -> tuple:
        r = list(row)
        if len(r) > 1 and "." not in r[1] and " " in r[1]:
            r[1] = r[1].replace(" ", ".", 1)
        return tuple(r)

    tsv_lines, cl_lines = Counter(map(tuple, tsv[1:])), Counter(map(tuple, cl[1:]))
    tsv_dot, cl_dot = Counter(map(_dot, tsv[1:])), Counter(map(_dot, cl[1:]))
    out["cell_list_copies"] = {
        "wa_tsv_header": tsv[0],
        "cell_lineage_header": cl[0],
        "wa_tsv_rows": len(tsv) - 1,
        "cell_lineage_rows": len(cl) - 1,
        "wa_tsv_fields_per_row": {str(k): v for k, v in sorted(Counter(len(r) for r in tsv[1:]).items())},
        "cell_lineage_fields_per_row": {str(k): v for k, v in sorted(Counter(len(r) for r in cl[1:]).items())},
        "rows_identical": sum((tsv_lines & cl_lines).values()),
        "rows_identical_if_lineage_space_equals_dot": sum((tsv_dot & cl_dot).values()),
        "wa_tsv_lineages_with_space": sum(1 for r in tsv[1:] if len(r) > 1 and " " in r[1].strip()),
        "cell_lineage_lineages_with_space": sum(1 for r in cl[1:] if len(r) > 1 and " " in r[1].strip()),
        "names_only_in_wa_tsv": sorted(set(wa_tsv) - set(cell_lineage)),
        "names_only_in_cell_lineage": sorted(set(cell_lineage) - set(wa_tsv)),
        "wa_tsv_slash_name_rows": sorted("\t".join(r[:2]) for r in tsv[1:] if "/" in r[0]),
        "wa_tsv": _byte_facts(F_WA_TSV),
        "cell_lineage": _byte_facts(F_LINEAGE),
    }

    # --- all_cell_info.csv --------------------------------------------------
    aci = list(csv.reader(io.StringIO(_text(F_ALL_CELL_INFO))))
    all_cell_info = [r[0] for r in aci[1:]]
    out["all_cell_info_csv"] = {
        "header": aci[0],
        "data_rows": len(aci) - 1,
        "fields_per_row": {str(k): v for k, v in sorted(Counter(len(r) for r in aci[1:]).items())},
        "type_values_over_cellspy302": dict(sorted(Counter(r[1] for r in aci[1:] if r[0] in set(cellspy302)).items())),
        **_byte_facts(F_ALL_CELL_INFO),
    }

    # --- Probes and set differences -----------------------------------------
    neuron_lists = {
        "cellspy302": cellspy302,
        "wormbase_herm": wormbase_herm,
        "ow_neurons": ow_neurons,
        "wna_ids": wna_ids,
        "individual": individual,
    }
    cell_sets = {
        "nemanode": nemanode,
        "wa_tsv": wa_tsv,
        "cell_lineage": cell_lineage,
        "all_cell_info": all_cell_info,
    }
    every = {**neuron_lists, **cell_sets, "wormbase_male": wormbase_male}
    out["sets"] = {k: len(set(v)) for k, v in sorted(every.items())}
    out["probe"] = {k: _probe(v, pharyngeal, k not in cell_sets) for k, v in sorted(every.items())}

    diff: dict = {}
    keys = sorted(neuron_lists)
    for a in keys:
        for b in keys:
            if a != b:
                diff[f"{a}_minus_{b}"] = sorted(set(neuron_lists[a]) - set(neuron_lists[b]))
    for a in keys:
        for b in sorted(cell_sets):
            diff[f"{a}_minus_{b}"] = sorted(set(neuron_lists[a]) - set(cell_sets[b]))
    for b in sorted(cell_sets):
        diff[f"{b}_minus_cellspy302_count"] = len(set(cell_sets[b]) - set(cellspy302))
    # The male-neuron column is compared only where it is informative.
    diff["wormbase_male_intersect_cellspy302"] = sorted(set(wormbase_male) & set(cellspy302))
    diff["wormbase_male_minus_individual"] = sorted(set(wormbase_male) - set(individual))
    diff["individual_minus_cellspy302_minus_wormbase_male"] = sorted(
        set(individual) - set(cellspy302) - set(wormbase_male)
    )
    out["diff"] = diff

    out["identical_name_sets"] = sorted(
        f"{a}=={b}" for a in keys for b in keys if a < b and set(neuron_lists[a]) == set(neuron_lists[b])
    )

    # --- Lineage strings of the cellspy302 names, compared across copies ----
    def _dot1(s: str) -> str:
        s = s.strip()
        return s.replace(" ", ".", 1) if "." not in s else s

    lineages: dict[str, dict[str, list[str]]] = {
        "individual": {},
        "ow_neurons": {},
        "wormbase_herm": {},
        "wa_tsv": {},
        "cell_lineage": {},
    }
    for r in in_rows:
        lineages["individual"].setdefault(r[0], []).append(r[2])
    for r in ow:
        lineages["ow_neurons"].setdefault(r[0], []).append(r[2])
    for r in data:
        if r[col_herm] == "1":
            lineages["wormbase_herm"].setdefault(r[0], []).append(r[1])
    for r in tsv[1:]:
        lineages["wa_tsv"].setdefault(r[0], []).append(r[1])
    for r in cl[1:]:
        lineages["cell_lineage"].setdefault(r[0], []).append(r[1])
    lin_out: dict = {}
    lkeys = sorted(lineages)
    for i, a in enumerate(lkeys):
        for b in lkeys[i + 1 :]:
            raw_equal = 0
            dis = []
            for n in cellspy302:
                la, lb = lineages[a].get(n), lineages[b].get(n)
                if la is None or lb is None:
                    continue
                if sorted(la) == sorted(lb):
                    raw_equal += 1
                if {_dot1(x) for x in la} != {_dot1(x) for x in lb}:
                    dis.append([n, " | ".join(la), " | ".join(lb)])
            lin_out[f"{a}_vs_{b}"] = {
                "names_compared": sum(1 for n in cellspy302 if n in lineages[a] and n in lineages[b]),
                "identical_as_written": raw_equal,
                "differ_if_first_space_equals_dot": dis,
            }
    out["lineage_comparison_over_cellspy302"] = lin_out

    # Raw rows for the names whose spelling differs between copies.
    probe_names = {"AVFL", "AVFR", "AVFL/R", "DB1", "DB3", "DB1/3", "DB3/1", "PHBR", "PHRB", "ADFL"}
    col_syn = header.index("Synonyms")
    out["rows_for_probe_names"] = {
        "individual": sorted(";".join(r) for r in in_rows if r[0] in probe_names),
        "ow_neurons": sorted(";".join(r) for r in ow if r[0] in probe_names),
        "wormbase_csv_name_lineage_synonyms": sorted(
            "\t".join((r[0], r[1], r[col_syn])) for r in data if r[0] in probe_names
        ),
        "wa_tsv": sorted("\t".join(r) for r in tsv[1:] if r[0] in probe_names),
        "cell_lineage": sorted("\t".join(r) for r in cl[1:] if r[0] in probe_names),
    }
    return out
